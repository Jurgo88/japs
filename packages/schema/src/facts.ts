import { z } from "zod";
import { RepoId } from "./projects.ts";

/**
 * Deterministic facts per project, extracted without an LLM. The only input to generation.
 * See docs/spec/ai-pipeline.md, step 1. Private repo content is for extraction only, never quoted.
 */

const DateTime = z.string().datetime();

export const TechCategory = z.enum([
  "language",
  "framework",
  "library",
  "ui",
  "styling",
  "backend",
  "service",
  "testing",
  "tooling",
  "hosting",
]);
export type TechCategory = z.infer<typeof TechCategory>;

/** A technology with the evidence it was found by, e.g. "dependency:@supabase/supabase-js". */
export const TechFact = z.object({
  name: z.string(),
  category: TechCategory,
  evidence: z.array(z.string()).min(1),
});
export type TechFact = z.infer<typeof TechFact>;

export const PackageFacts = z.object({
  /** Path of the package.json in the repo, "" for the root. */
  path: z.string(),
  name: z.string().nullable(),
  description: z.string().nullable(),
  dependencies: z.array(z.string()),
  devDependencies: z.array(z.string()),
});
export type PackageFacts = z.infer<typeof PackageFacts>;

export const RepoFacts = z.object({
  id: RepoId,
  /** False when the token can't see the repo; everything below is then null/empty. */
  accessible: z.boolean(),
  private: z.boolean(),
  /** Cache key: repo facts are reused while pushedAt is unchanged. */
  pushedAt: DateTime.nullable(),
  description: z.string().nullable(),
  topics: z.array(z.string()),
  primaryLanguage: z.string().nullable(),
  /** Share of code in percent, one decimal, largest first. */
  languages: z.record(z.string(), z.number()),
  commits: z
    .object({
      count: z.number().int(),
      first: DateTime.nullable(),
      last: DateTime.nullable(),
    })
    .nullable(),
  pullRequests: z.number().int().nullable(),
  readme: z
    .object({
      excerpt: z.string(),
      headings: z.array(z.string()),
    })
    .nullable(),
  /** Root package.json first, then workspace packages. Empty when there is none. */
  packages: z.array(PackageFacts),
});
export type RepoFacts = z.infer<typeof RepoFacts>;

export const NetlifyFunction = z.object({
  name: z.string(),
  /** Generated by a framework adapter (e.g. "nuxt@4.6.0"), not written by hand. */
  generator: z.string().nullable(),
  runtime: z.string().nullable(),
});
export type NetlifyFunction = z.infer<typeof NetlifyFunction>;

export const LighthouseScores = z.object({
  performance: z.number().nullable(),
  accessibility: z.number().nullable(),
  bestPractices: z.number().nullable(),
  seo: z.number().nullable(),
});
export type LighthouseScores = z.infer<typeof LighthouseScores>;

export const LiveSiteFacts = z.object({
  status: z.number().int(),
  finalUrl: z.string().url(),
  title: z.string().nullable(),
  description: z.string().nullable(),
  lang: z.string().nullable(),
  /** og:* meta tags without the "og:" prefix, e.g. { title, description, image }. */
  og: z.record(z.string(), z.string()),
});
export type LiveSiteFacts = z.infer<typeof LiveSiteFacts>;

export const SiteFacts = z.object({
  id: z.string(),
  /** Absent for Netlify (the original provider), so older facts keep their hash. */
  provider: z.enum(["cloudflare"]).optional(),
  domain: z.string(),
  url: z.string().url(),
  framework: z.string().nullable(),
  lastDeployAt: DateTime.nullable(),
  deploy: z
    .object({
      commitMessage: z.string().nullable(),
      committer: z.string().nullable(),
      functions: z.array(NetlifyFunction),
      scheduledFunctions: z.array(z.object({ name: z.string(), cron: z.string() })),
      edgeFunctions: z.boolean(),
      lighthouse: LighthouseScores.nullable(),
    })
    .nullable(),
  /** Null when the site couldn't be fetched. */
  live: LiveSiteFacts.nullable(),
});
export type SiteFacts = z.infer<typeof SiteFacts>;

export const ProjectFacts = z.object({
  key: z.string(),
  title: z.string(),
  private: z.boolean(),
  /** SHA-256 of the facts (without hash itself); analysis reruns only when it changes. */
  hash: z.string().regex(/^[0-9a-f]{64}$/),
  repos: z.array(RepoFacts),
  sites: z.array(SiteFacts),
  /** Derived from dependencies, languages, topics and Netlify; the only source of tags. */
  tech: z.array(TechFact),
});
export type ProjectFacts = z.infer<typeof ProjectFacts>;

export const FactsFile = z.object({
  version: z.literal(1),
  generatedAt: DateTime,
  projects: z.array(ProjectFacts),
  /** Non-fatal extraction problems (rate limit, unreachable site, broken package.json). */
  warnings: z.array(z.string()),
});
export type FactsFile = z.infer<typeof FactsFile>;
